<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Delete Product API
|--------------------------------------------------------------------------
| File:
| api/v1/products/delete.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/database.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| DELETE Only
|--------------------------------------------------------------------------
*/

if (requestMethod() !== 'DELETE') {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Request
|--------------------------------------------------------------------------
*/

$data = getJsonInput();

$id = cleanInt(
    $data['id'] ?? $_GET['id'] ?? 0
);


if ($id <= 0) {

    errorResponse(
        'رقم المنتج غير صحيح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Database
|--------------------------------------------------------------------------
*/

try {

    $db = getDatabaseConnection();


    /*
    |--------------------------------------------------------------------------
    | Find Product
    |--------------------------------------------------------------------------
    */

    $productStmt = $db->prepare(
        "
        SELECT
            id,
            name,
            sku,
            image

        FROM products

        WHERE id = :id

        LIMIT 1
        "
    );

    $productStmt->execute([
        ':id' => $id
    ]);


    $product = $productStmt->fetch();


    if (!$product) {

        errorResponse(
            'المنتج غير موجود.',
            404
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Delete Product
    |--------------------------------------------------------------------------
    */

    $deleteStmt = $db->prepare(
        "
        DELETE FROM products

        WHERE id = :id
        "
    );


    $deleteStmt->execute([
        ':id' => $id
    ]);


    /*
    |--------------------------------------------------------------------------
    | Verify
    |--------------------------------------------------------------------------
    */

    if ($deleteStmt->rowCount() === 0) {

        errorResponse(
            'تعذر حذف المنتج.',
            500
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [

            'deleted' =>
                true,

            'product_id' =>
                $id,

            'product_name' =>
                $product['name']

        ],

        'تم حذف المنتج بنجاح.'
    );


} catch (PDOException $e) {

    error_log(
        'Delete Product PDO Error: ' .
        $e->getMessage()
    );


    /*
    |--------------------------------------------------------------------------
    | Foreign Key / Related Data
    |--------------------------------------------------------------------------
    */

    if ($e->getCode() === '23000') {

        errorResponse(
            'لا يمكن حذف المنتج لأنه مرتبط ببيانات أخرى.',
            409
        );

    }


    errorResponse(
        'حدث خطأ أثناء حذف المنتج.',
        500
    );


} catch (Throwable $e) {

    error_log(
        'Delete Product Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء حذف المنتج.',
        500
    );

}
