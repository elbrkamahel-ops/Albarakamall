<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Update Order Status API
|--------------------------------------------------------------------------
| File:
| api/v1/orders/update-status.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/database.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| PUT / PATCH Only
|--------------------------------------------------------------------------
*/

if (
    requestMethod() !== 'PUT' &&
    requestMethod() !== 'PATCH'
) {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Request
|--------------------------------------------------------------------------
*/

$data = getJsonInput();

if (empty($data)) {
    $data = $_POST;
}


/*
|--------------------------------------------------------------------------
| Input
|--------------------------------------------------------------------------
*/

$id = cleanInt(
    $data['id'] ?? $_GET['id'] ?? 0
);

$status = cleanString(
    $data['status'] ?? ''
);


/*
|--------------------------------------------------------------------------
| Validation
|--------------------------------------------------------------------------
*/

if ($id <= 0) {

    errorResponse(
        'رقم الطلب غير صحيح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Allowed Statuses
|--------------------------------------------------------------------------
*/

$allowedStatuses = [

    'pending',
    'confirmed',
    'preparing',
    'out_for_delivery',
    'delivered',
    'cancelled'

];


if (
    !in_array(
        $status,
        $allowedStatuses,
        true
    )
) {

    errorResponse(
        'حالة الطلب غير صحيحة.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Database
|--------------------------------------------------------------------------
*/

try {

    $db = getDatabaseConnection();


    /*
    |--------------------------------------------------------------------------
    | Get Current Order
    |--------------------------------------------------------------------------
    */

    $orderStmt = $db->prepare(
        "
        SELECT

            id,
            order_number,
            status

        FROM orders

        WHERE id = :id

        LIMIT 1
        "
    );


    $orderStmt->execute([
        ':id' => $id
    ]);


    $order = $orderStmt->fetch();


    if (!$order) {

        errorResponse(
            'الطلب غير موجود.',
            404
        );

    }


    $oldStatus =
        $order['status'];


    /*
    |--------------------------------------------------------------------------
    | No Change
    |--------------------------------------------------------------------------
    */

    if (
        $oldStatus === $status
    ) {

        successResponse(
            [
                'order' => [
                    'id' =>
                        (int)
                        $order['id'],

                    'order_number' =>
                        $order['order_number'],

                    'old_status' =>
                        $oldStatus,

                    'status' =>
                        $status
                ]
            ],
            'حالة الطلب بالفعل هي الحالة المطلوبة.'
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Prevent Changes After Delivery / Cancellation
    |--------------------------------------------------------------------------
    */

    if (
        in_array(
            $oldStatus,
            [
                'delivered',
                'cancelled'
            ],
            true
        )
    ) {

        errorResponse(
            'لا يمكن تغيير حالة طلب تم تسليمه أو إلغاؤه.',
            409
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Status Flow
    |--------------------------------------------------------------------------
    */

    $statusOrder = [

        'pending' =>
            1,

        'confirmed' =>
            2,

        'preparing' =>
            3,

        'out_for_delivery' =>
            4,

        'delivered' =>
            5

    ];


    /*
    |--------------------------------------------------------------------------
    | Prevent Invalid Backward Status
    |--------------------------------------------------------------------------
    */

    if (
        $status !== 'cancelled' &&
        isset(
            $statusOrder[$oldStatus],
            $statusOrder[$status]
        ) &&
        $statusOrder[$status]
            < $statusOrder[$oldStatus]
    ) {

        errorResponse(
            'لا يمكن إرجاع الطلب إلى حالة سابقة.',
            409
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Update
    |--------------------------------------------------------------------------
    */

    $updateStmt = $db->prepare(
        "
        UPDATE orders

        SET

            status = :status

        WHERE id = :id
        "
    );


    $updateStmt->execute([

        ':status' =>
            $status,

        ':id' =>
            $id

    ]);


    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [

            'order' => [

                'id' =>
                    (int)
                    $order['id'],

                'order_number' =>
                    $order['order_number'],

                'old_status' =>
                    $oldStatus,

                'status' =>
                    $status

            ]

        ],

        'تم تحديث حالة الطلب بنجاح.'
    );


} catch (Throwable $e) {

    error_log(
        'Update Order Status API Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء تحديث حالة الطلب.',
        500
    );

}
