<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Delete Uploaded Product Image API
|--------------------------------------------------------------------------
| File:
| api/v1/uploads/delete.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| DELETE Only
|--------------------------------------------------------------------------
*/

if (requestMethod() !== 'DELETE') {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Request
|--------------------------------------------------------------------------
*/

$data = getJsonInput();

$filename = cleanString(
    $data['filename'] ?? $_GET['filename'] ?? ''
);


if ($filename === '') {

    errorResponse(
        'اسم الملف مطلوب.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Security
|--------------------------------------------------------------------------
| نسمح فقط بأسماء الملفات داخل مجلد products
|--------------------------------------------------------------------------
*/

$filename = basename($filename);


/*
|--------------------------------------------------------------------------
| Allowed Extensions
|--------------------------------------------------------------------------
*/

$allowedExtensions = [
    'jpg',
    'jpeg',
    'png',
    'webp'
];


$extension =
    strtolower(
        pathinfo(
            $filename,
            PATHINFO_EXTENSION
        )
    );


if (
    !in_array(
        $extension,
        $allowedExtensions,
        true
    )
) {

    errorResponse(
        'نوع الملف غير مسموح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Required Filename Pattern
|--------------------------------------------------------------------------
*/

if (
    !preg_match(
        '/^product-[0-9]{14}-[a-f0-9]+\.(jpg|jpeg|png|webp)$/i',
        $filename
    )
) {

    errorResponse(
        'اسم الملف غير صالح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Product Upload Directory
|--------------------------------------------------------------------------
*/

$uploadDirectory =
    dirname(
        __DIR__,
        3
    ) .
    '/uploads/products/';


$filePath =
    $uploadDirectory .
    $filename;


/*
|--------------------------------------------------------------------------
| Check File
|--------------------------------------------------------------------------
*/

if (
    !is_file($filePath)
) {

    errorResponse(
        'الصورة غير موجودة.',
        404
    );

}


/*
|--------------------------------------------------------------------------
| Delete
|--------------------------------------------------------------------------
*/

if (
    !unlink($filePath)
) {

    errorResponse(
        'تعذر حذف الصورة.',
        500
    );

}


/*
|--------------------------------------------------------------------------
| Response
|--------------------------------------------------------------------------
*/

successResponse(
    [

        'deleted' =>
            true,

        'filename' =>
            $filename,

        'path' =>
            '/uploads/products/' .
            $filename

    ],

    'تم حذف الصورة بنجاح.'
);
