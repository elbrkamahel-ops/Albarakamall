<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Product Image Upload API
|--------------------------------------------------------------------------
| File:
| api/v1/uploads/product-image.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| POST Only
|--------------------------------------------------------------------------
*/

if (requestMethod() !== 'POST') {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Check Upload
|--------------------------------------------------------------------------
*/

if (
    !isset($_FILES['image'])
) {

    errorResponse(
        'لم يتم إرسال صورة.',
        422
    );

}


$file = $_FILES['image'];


/*
|--------------------------------------------------------------------------
| Upload Error
|--------------------------------------------------------------------------
*/

if (
    $file['error'] !== UPLOAD_ERR_OK
) {

    errorResponse(
        'حدث خطأ أثناء رفع الصورة.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| File Size
|--------------------------------------------------------------------------
| الحد الأقصى: 5MB
|--------------------------------------------------------------------------
*/

$maxSize =
    5 * 1024 * 1024;


if (
    $file['size'] > $maxSize
) {

    errorResponse(
        'حجم الصورة يجب ألا يتجاوز 5 ميجابايت.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Validate MIME Type
|--------------------------------------------------------------------------
*/

$finfo =
    new finfo(
        FILEINFO_MIME_TYPE
    );


$mime =
    $finfo->file(
        $file['tmp_name']
    );


$allowedTypes = [

    'image/jpeg' =>
        'jpg',

    'image/png' =>
        'png',

    'image/webp' =>
        'webp'

];


if (
    !isset(
        $allowedTypes[$mime]
    )
) {

    errorResponse(
        'نوع الصورة غير مسموح. استخدم JPG أو PNG أو WEBP.',
        422
    );

}


$extension =
    $allowedTypes[$mime];


/*
|--------------------------------------------------------------------------
| Verify Real Image
|--------------------------------------------------------------------------
*/

$imageInfo =
    @getimagesize(
        $file['tmp_name']
    );


if (
    $imageInfo === false
) {

    errorResponse(
        'الملف المرسل ليس صورة صحيحة.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Image Dimensions
|--------------------------------------------------------------------------
*/

$width =
    (int)
    $imageInfo[0];

$height =
    (int)
    $imageInfo[1];


if (
    $width < 100 ||
    $height < 100
) {

    errorResponse(
        'أبعاد الصورة صغيرة جدًا.',
        422
    );

}


if (
    $width > 5000 ||
    $height > 5000
) {

    errorResponse(
        'أبعاد الصورة كبيرة جدًا.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Upload Directory
|--------------------------------------------------------------------------
*/

$uploadDirectory =
    dirname(
        __DIR__,
        3
    ) .
    '/uploads/products/';


/*
|--------------------------------------------------------------------------
| Create Directory
|--------------------------------------------------------------------------
*/

if (
    !is_dir(
        $uploadDirectory
    )
) {

    if (
        !mkdir(
            $uploadDirectory,
            0755,
            true
        )
    ) {

        errorResponse(
            'تعذر إنشاء مجلد الصور.',
            500
        );

    }

}


/*
|--------------------------------------------------------------------------
| Generate Safe Filename
|--------------------------------------------------------------------------
*/

$filename =
    'product-' .
    date('YmdHis') .
    '-' .
    bin2hex(
        random_bytes(8)
    ) .
    '.' .
    $extension;


$targetPath =
    $uploadDirectory .
    $filename;


/*
|--------------------------------------------------------------------------
| Move File
|--------------------------------------------------------------------------
*/

if (
    !move_uploaded_file(
        $file['tmp_name'],
        $targetPath
    )
) {

    errorResponse(
        'تعذر حفظ الصورة.',
        500
    );

}


/*
|--------------------------------------------------------------------------
| Public URL
|--------------------------------------------------------------------------
*/

$relativePath =
    '/uploads/products/' .
    $filename;


/*
|--------------------------------------------------------------------------
| Response
|--------------------------------------------------------------------------
*/

successResponse(
    [

        'file' => [
            'name' =>
                $filename,

            'path' =>
                $relativePath,

            'url' =>
                $relativePath,

            'mime' =>
                $mime,

            'size' =>
                (int)
                $file['size'],

            'width' =>
                $width,

            'height' =>
                $height
        ]

    ],

    'تم رفع صورة المنتج بنجاح.'
);
