<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Current Admin API
|--------------------------------------------------------------------------
| File:
| api/v1/auth/me.php
|--------------------------------------------------------------------------
*/


require_once __DIR__ . '/../../../config/config.php';

require_once __DIR__ . '/../../../config/database.php';

require_once __DIR__ . '/../../../config/auth.php';



/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();



/*
|--------------------------------------------------------------------------
| Allow GET Only
|--------------------------------------------------------------------------
*/

if (
    requestMethod() !== 'GET'
) {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}



/*
|--------------------------------------------------------------------------
| Check Login
|--------------------------------------------------------------------------
*/

if (
    !isAdminLoggedIn()
) {

    errorResponse(
        'غير مسجل الدخول.',
        401
    );

}



/*
|--------------------------------------------------------------------------
| Current Admin
|--------------------------------------------------------------------------
*/

$admin =
    getCurrentAdmin();



/*
|--------------------------------------------------------------------------
| Validate Admin
|--------------------------------------------------------------------------
*/

if (
    !$admin ||
    empty($admin['id'])
) {

    logoutAdmin();


    errorResponse(
        'جلسة الدخول غير صالحة.',
        401
    );

}



/*
|--------------------------------------------------------------------------
| Get Fresh Admin Data
|--------------------------------------------------------------------------
*/

try {

    $db =
        getDatabaseConnection();


    $stmt =
        $db->prepare(
            "
            SELECT

                id,

                name,

                email,

                role,

                status,

                last_login_at,

                created_at

            FROM admins

            WHERE id = :id

            LIMIT 1
            "
        );


    $stmt->execute(
        [
            ':id' =>
                $admin['id']
        ]
    );


    $freshAdmin =
        $stmt->fetch();



    /*
    |--------------------------------------------------------------------------
    | Admin Not Found
    |--------------------------------------------------------------------------
    */

    if (
        !$freshAdmin
    ) {

        logoutAdmin();


        errorResponse(
            'حساب المدير غير موجود.',
            401
        );

    }



    /*
    |--------------------------------------------------------------------------
    | Check Status
    |--------------------------------------------------------------------------
    */

    if (
        $freshAdmin['status'] !== 'active'
    ) {

        logoutAdmin();


        errorResponse(
            'حساب المدير غير نشط.',
            403
        );

    }



    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [
            'logged_in' => true,

            'admin' => [

                'id' =>
                    (int)
                    $freshAdmin['id'],

                'name' =>
                    $freshAdmin['name'],

                'email' =>
                    $freshAdmin['email'],

                'role' =>
                    $freshAdmin['role'],

                'status' =>
                    $freshAdmin['status'],

                'last_login_at' =>
                    $freshAdmin['last_login_at'],

                'created_at' =>
                    $freshAdmin['created_at']

            ],

            'csrf_token' =>
                getCsrfToken()

        ],

        'جلسة المدير صالحة.'
    );


} catch (
    Throwable $e
) {


    /*
    |--------------------------------------------------------------------------
    | Internal Error Log
    |--------------------------------------------------------------------------
    */

    error_log(
        'Admin Me API Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء التحقق من جلسة المدير.',
        500
    );

}
