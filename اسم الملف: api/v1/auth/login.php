<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Admin Login API
|--------------------------------------------------------------------------
| File:
| api/v1/auth/login.php
|--------------------------------------------------------------------------
*/


require_once __DIR__ . '/../../../config/config.php';

require_once __DIR__ . '/../../../config/database.php';

require_once __DIR__ . '/../../../config/auth.php';



/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();



/*
|--------------------------------------------------------------------------
| Allow POST Only
|--------------------------------------------------------------------------
*/

if (
    requestMethod() !== 'POST'
) {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}



/*
|--------------------------------------------------------------------------
| Start Session
|--------------------------------------------------------------------------
*/

startAdminSession();



/*
|--------------------------------------------------------------------------
| Read Request
|--------------------------------------------------------------------------
*/

$data =
    getJsonInput();



/*
|--------------------------------------------------------------------------
| Support Form Data
|--------------------------------------------------------------------------
*/

if (
    empty($data)
) {

    $data = $_POST;

}



/*
|--------------------------------------------------------------------------
| Get Credentials
|--------------------------------------------------------------------------
*/

$email =
    cleanString(
        $data['email'] ?? ''
    );


$password =
    (string) (
        $data['password'] ?? ''
    );



/*
|--------------------------------------------------------------------------
| Validation
|--------------------------------------------------------------------------
*/

if (
    $email === ''
) {

    errorResponse(
        'البريد الإلكتروني مطلوب.',
        422
    );

}


if (
    !filter_var(
        $email,
        FILTER_VALIDATE_EMAIL
    )
) {

    errorResponse(
        'البريد الإلكتروني غير صحيح.',
        422
    );

}


if (
    $password === ''
) {

    errorResponse(
        'كلمة المرور مطلوبة.',
        422
    );

}



/*
|--------------------------------------------------------------------------
| Login
|--------------------------------------------------------------------------
*/

try {

    $login =
        loginAdmin(
            $email,
            $password
        );


    if (
        !$login
    ) {

        /*
        | لا نكشف هل البريد موجود أم لا.
        */

        errorResponse(
            'بيانات تسجيل الدخول غير صحيحة.',
            401
        );

    }



    /*
    |--------------------------------------------------------------------------
    | Update Last Login
    |--------------------------------------------------------------------------
    */

    $adminId =
        getCurrentAdminId();


    if (
        $adminId
    ) {

        $db =
            getDatabaseConnection();


        $stmt =
            $db->prepare(
                "
                UPDATE admins

                SET last_login_at =
                    CURRENT_TIMESTAMP

                WHERE id = :id
                "
            );


        $stmt->execute(
            [
                ':id' =>
                    $adminId
            ]
        );

    }



    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [
            'admin' =>
                getCurrentAdmin(),

            'csrf_token' =>
                getCsrfToken()
        ],
        'تم تسجيل الدخول بنجاح.'
    );


} catch (
    Throwable $e
) {


    /*
    | تسجيل الخطأ داخليًا
    */

    error_log(
        'Admin Login Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء تسجيل الدخول.',
        500
    );

}
