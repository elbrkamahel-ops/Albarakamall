<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Delete Product API
|--------------------------------------------------------------------------
| File:
| api/v1/products/delete.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/database.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| DELETE Only
|--------------------------------------------------------------------------
*/

if (requestMethod() !== 'DELETE') {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Request
|--------------------------------------------------------------------------
*/

$data = getJsonInput();

$id = cleanInt(
    $data['id'] ?? $_GET['id'] ?? 0
);


if ($id <= 0) {

    errorResponse(
        'رقم المنتج غير صحيح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Database
|--------------------------------------------------------------------------
*/

try {

    $db =
        getDatabaseConnection();


    /*
    |--------------------------------------------------------------------------
    | Start Transaction
    |--------------------------------------------------------------------------
    */

    $db->beginTransaction();


    /*
    |--------------------------------------------------------------------------
    | Get Product
    |--------------------------------------------------------------------------
    */

    $productStmt =
        $db->prepare(
            "
            SELECT

                id,
                name,
                slug,
                image

            FROM products

            WHERE id = :id

            LIMIT 1

            FOR UPDATE
            "
        );


    $productStmt->execute([
        ':id' => $id
    ]);


    $product =
        $productStmt->fetch();


    /*
    |--------------------------------------------------------------------------
    | Product Not Found
    |--------------------------------------------------------------------------
    */

    if (!$product) {

        $db->rollBack();

        errorResponse(
            'المنتج غير موجود.',
            404
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Check Existing Orders
    |--------------------------------------------------------------------------
    */

    $ordersStmt =
        $db->prepare(
            "
            SELECT COUNT(*)

            FROM order_items

            WHERE product_id = :product_id
            "
        );


    $ordersStmt->execute([
        ':product_id' => $id
    ]);


    $ordersCount =
        (int)
        $ordersStmt->fetchColumn();


    /*
    |--------------------------------------------------------------------------
    | Protect Historical Orders
    |--------------------------------------------------------------------------
    */

    if ($ordersCount > 0) {

        $db->rollBack();

        errorResponse(
            'لا يمكن حذف المنتج لأنه مرتبط بـ ' .
            $ordersCount .
            ' عنصر طلب سابق. يمكنك إيقافه بدلًا من حذفه.',
            409
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Delete Product
    |--------------------------------------------------------------------------
    */

    $deleteStmt =
        $db->prepare(
            "
            DELETE FROM products

            WHERE id = :id
            "
        );


    $deleteStmt->execute([
        ':id' => $id
    ]);


    /*
    |--------------------------------------------------------------------------
    | Verify Delete
    |--------------------------------------------------------------------------
    */

    if (
        $deleteStmt->rowCount() === 0
    ) {

        throw new RuntimeException(
            'تعذر حذف المنتج.'
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Commit
    |--------------------------------------------------------------------------
    */

    $db->commit();


    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [

            'deleted' =>
                true,

            'product' => [

                'id' =>
                    (int)
                    $product['id'],

                'name' =>
                    $product['name'],

                'slug' =>
                    $product['slug']

            ]

        ],

        'تم حذف المنتج بنجاح.'
    );


} catch (PDOException $e) {

    if (
        isset($db) &&
        $db->inTransaction()
    ) {

        $db->rollBack();

    }


    error_log(
        'Delete Product PDO Error: ' .
        $e->getMessage()
    );


    if (
        $e->getCode() === '23000'
    ) {

        errorResponse(
            'لا يمكن حذف المنتج لأنه مرتبط ببيانات أخرى.',
            409
        );

    }


    errorResponse(
        'حدث خطأ أثناء حذف المنتج.',
        500
    );


} catch (Throwable $e) {

    if (
        isset($db) &&
        $db->inTransaction()
    ) {

        $db->rollBack();

    }


    error_log(
        'Delete Product Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء حذف المنتج.',
        500
    );

}
