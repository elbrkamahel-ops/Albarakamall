<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Cancel Order API
|--------------------------------------------------------------------------
| File:
| api/v1/orders/cancel.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/database.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| POST Only
|--------------------------------------------------------------------------
*/

if (requestMethod() !== 'POST') {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Request
|--------------------------------------------------------------------------
*/

$data = getJsonInput();

if (empty($data)) {
    $data = $_POST;
}


/*
|--------------------------------------------------------------------------
| Order ID
|--------------------------------------------------------------------------
*/

$orderId = cleanInt(
    $data['id'] ?? $_GET['id'] ?? 0
);


if ($orderId <= 0) {

    errorResponse(
        'رقم الطلب غير صحيح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Database
|--------------------------------------------------------------------------
*/

try {

    $db = getDatabaseConnection();


    /*
    |--------------------------------------------------------------------------
    | Transaction
    |--------------------------------------------------------------------------
    */

    $db->beginTransaction();


    /*
    |--------------------------------------------------------------------------
    | Lock Order
    |--------------------------------------------------------------------------
    */

    $orderStmt = $db->prepare(
        "
        SELECT

            id,
            order_number,
            status

        FROM orders

        WHERE id = :id

        LIMIT 1

        FOR UPDATE
        "
    );


    $orderStmt->execute([
        ':id' => $orderId
    ]);


    $order = $orderStmt->fetch();


    if (!$order) {

        $db->rollBack();

        errorResponse(
            'الطلب غير موجود.',
            404
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Already Cancelled
    |--------------------------------------------------------------------------
    */

    if (
        $order['status'] === 'cancelled'
    ) {

        $db->rollBack();

        successResponse(
            [

                'order' => [

                    'id' =>
                        (int)
                        $order['id'],

                    'order_number' =>
                        $order['order_number'],

                    'status' =>
                        'cancelled'

                ]

            ],

            'الطلب ملغي بالفعل.'
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Delivered
    |--------------------------------------------------------------------------
    */

    if (
        $order['status'] === 'delivered'
    ) {

        $db->rollBack();

        errorResponse(
            'لا يمكن إلغاء طلب تم تسليمه.',
            409
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Get Items
    |--------------------------------------------------------------------------
    */

    $itemsStmt = $db->prepare(
        "
        SELECT

            product_id,
            quantity

        FROM order_items

        WHERE order_id = :order_id
        "
    );


    $itemsStmt->execute([
        ':order_id' => $orderId
    ]);


    $items = $itemsStmt->fetchAll();


    /*
    |--------------------------------------------------------------------------
    | Return Stock
    |--------------------------------------------------------------------------
    */

    $stockStmt = $db->prepare(
        "
        UPDATE products

        SET stock =
            stock + :quantity

        WHERE id = :id
        "
    );


    foreach (
        $items as $item
    ) {

        $productId =
            (int)
            $item['product_id'];

        $quantity =
            (float)
            $item['quantity'];


        if (
            $productId <= 0 ||
            $quantity <= 0
        ) {

            continue;

        }


        $stockStmt->execute([

            ':quantity' =>
                $quantity,

            ':id' =>
                $productId

        ]);

    }


    /*
    |--------------------------------------------------------------------------
    | Update Order
    |--------------------------------------------------------------------------
    */

    $updateStmt = $db->prepare(
        "
        UPDATE orders

        SET status = :status

        WHERE id = :id
        "
    );


    $updateStmt->execute([

        ':status' =>
            'cancelled',

        ':id' =>
            $orderId

    ]);


    /*
    |--------------------------------------------------------------------------
    | Commit
    |--------------------------------------------------------------------------
    */

    $db->commit();


    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [

            'order' => [

                'id' =>
                    (int)
                    $order['id'],

                'order_number' =>
                    $order['order_number'],

                'old_status' =>
                    $order['status'],

                'status' =>
                    'cancelled',

                'stock_restored' =>
                    true

            ]

        ],

        'تم إلغاء الطلب وإرجاع المنتجات إلى المخزون.'
    );


} catch (Throwable $e) {

    /*
    |--------------------------------------------------------------------------
    | Rollback
    |--------------------------------------------------------------------------
    */

    if (
        isset($db) &&
        $db->inTransaction()
    ) {

        $db->rollBack();

    }


    error_log(
        'Cancel Order API Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء إلغاء الطلب.',
        500
    );

}
