<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Delete Order API
|--------------------------------------------------------------------------
| File:
| api/v1/orders/delete.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/database.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| DELETE Only
|--------------------------------------------------------------------------
*/

if (requestMethod() !== 'DELETE') {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Request
|--------------------------------------------------------------------------
*/

$data = getJsonInput();

$orderId = cleanInt(
    $data['id'] ?? $_GET['id'] ?? 0
);


if ($orderId <= 0) {

    errorResponse(
        'رقم الطلب غير صحيح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Database
|--------------------------------------------------------------------------
*/

try {

    $db = getDatabaseConnection();


    /*
    |--------------------------------------------------------------------------
    | Transaction
    |--------------------------------------------------------------------------
    */

    $db->beginTransaction();


    /*
    |--------------------------------------------------------------------------
    | Get Order
    |--------------------------------------------------------------------------
    */

    $orderStmt = $db->prepare(
        "
        SELECT

            id,
            order_number,
            status

        FROM orders

        WHERE id = :id

        LIMIT 1

        FOR UPDATE
        "
    );


    $orderStmt->execute([
        ':id' => $orderId
    ]);


    $order = $orderStmt->fetch();


    if (!$order) {

        $db->rollBack();

        errorResponse(
            'الطلب غير موجود.',
            404
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Only Cancelled Orders
    |--------------------------------------------------------------------------
    */

    if (
        $order['status'] !== 'cancelled'
    ) {

        $db->rollBack();

        errorResponse(
            'لا يمكن حذف طلب غير ملغي. قم بإلغاء الطلب أولًا.',
            409
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Delete Order Items
    |--------------------------------------------------------------------------
    */

    $itemsStmt = $db->prepare(
        "
        DELETE FROM order_items

        WHERE order_id = :order_id
        "
    );


    $itemsStmt->execute([
        ':order_id' => $orderId
    ]);


    /*
    |--------------------------------------------------------------------------
    | Delete Order
    |--------------------------------------------------------------------------
    */

    $deleteStmt = $db->prepare(
        "
        DELETE FROM orders

        WHERE id = :id

        AND status = 'cancelled'
        "
    );


    $deleteStmt->execute([
        ':id' => $orderId
    ]);


    if (
        $deleteStmt->rowCount() === 0
    ) {

        throw new RuntimeException(
            'تعذر حذف الطلب.'
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Commit
    |--------------------------------------------------------------------------
    */

    $db->commit();


    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [

            'deleted' =>
                true,

            'order' => [

                'id' =>
                    (int)
                    $order['id'],

                'order_number' =>
                    $order['order_number'],

                'status' =>
                    $order['status']

            ]

        ],

        'تم حذف الطلب بنجاح.'
    );


} catch (Throwable $e) {

    /*
    |--------------------------------------------------------------------------
    | Rollback
    |--------------------------------------------------------------------------
    */

    if (
        isset($db) &&
        $db->inTransaction()
    ) {

        $db->rollBack();

    }


    error_log(
        'Delete Order API Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء حذف الطلب.',
        500
    );

}
