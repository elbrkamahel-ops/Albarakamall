<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Categories List API
|--------------------------------------------------------------------------
| File:
| api/v1/categories/list.php
|--------------------------------------------------------------------------
*/


require_once __DIR__ . '/../../../config/config.php';

require_once __DIR__ . '/../../../config/database.php';



/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();



/*
|--------------------------------------------------------------------------
| Allow GET Only
|--------------------------------------------------------------------------
*/

if (
    requestMethod() !== 'GET'
) {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}



/*
|--------------------------------------------------------------------------
| Database
|--------------------------------------------------------------------------
*/

try {

    $db =
        getDatabaseConnection();



    /*
    |--------------------------------------------------------------------------
    | Query Parameters
    |--------------------------------------------------------------------------
    */

    $status =
        cleanString(
            $_GET['status'] ?? 'active'
        );


    $includeInactive =
        isset(
            $_GET['include_inactive']
        ) &&
        cleanBool(
            $_GET['include_inactive']
        );



    /*
    |--------------------------------------------------------------------------
    | Build Query
    |--------------------------------------------------------------------------
    */

    $sql = "

        SELECT

            id,

            name,

            slug,

            description,

            image,

            icon,

            sort_order,

            status,

            created_at,

            updated_at

        FROM categories

    ";


    $params = [];



    /*
    |--------------------------------------------------------------------------
    | Status Filter
    |--------------------------------------------------------------------------
    */

    if (
        !$includeInactive
    ) {

        $sql .= "
            WHERE status = :status
        ";

        $params[
            ':status'
        ] =
            $status ?: 'active';

    }



    /*
    |--------------------------------------------------------------------------
    | Ordering
    |--------------------------------------------------------------------------
    */

    $sql .= "

        ORDER BY

            sort_order ASC,

            id ASC

    ";



    /*
    |--------------------------------------------------------------------------
    | Execute
    |--------------------------------------------------------------------------
    */

    $stmt =
        $db->prepare(
            $sql
        );


    $stmt->execute(
        $params
    );


    $categories =
        $stmt->fetchAll();



    /*
    |--------------------------------------------------------------------------
    | Format Data
    |--------------------------------------------------------------------------
    */

    $result =
        array_map(
            function (
                $category
            ) {

                return [

                    'id' =>
                        (int)
                        $category['id'],

                    'name' =>
                        $category['name'],

                    'slug' =>
                        $category['slug'],

                    'description' =>
                        $category['description'],

                    'image' =>
                        $category['image'],

                    'icon' =>
                        $category['icon'],

                    'sort_order' =>
                        (int)
                        $category['sort_order'],

                    'status' =>
                        $category['status'],

                    'created_at' =>
                        $category['created_at'],

                    'updated_at' =>
                        $category['updated_at']

                ];

            },
            $categories
        );



    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [
            'categories' =>
                $result,

            'count' =>
                count($result)

        ],
        'تم تحميل الأقسام بنجاح.'
    );


} catch (
    Throwable $e
) {


    /*
    |--------------------------------------------------------------------------
    | Internal Error Log
    |--------------------------------------------------------------------------
    */

    error_log(
        'Categories List API Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء تحميل الأقسام.',
        500
    );

}
