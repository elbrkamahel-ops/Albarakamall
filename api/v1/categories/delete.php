<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Delete Category API
|--------------------------------------------------------------------------
| File:
| api/v1/categories/delete.php
|--------------------------------------------------------------------------
*/

require_once __DIR__ . '/../../../config/config.php';
require_once __DIR__ . '/../../../config/database.php';
require_once __DIR__ . '/../../../config/auth.php';


/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();


/*
|--------------------------------------------------------------------------
| Method
|--------------------------------------------------------------------------
*/

if (requestMethod() !== 'DELETE') {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}


/*
|--------------------------------------------------------------------------
| Authentication
|--------------------------------------------------------------------------
*/

requireAdminLogin();

requireCsrfToken();


/*
|--------------------------------------------------------------------------
| Request Data
|--------------------------------------------------------------------------
*/

$data = getJsonInput();


$id = cleanInt(
    $data['id'] ?? $_GET['id'] ?? 0
);


if ($id <= 0) {

    errorResponse(
        'رقم القسم غير صحيح.',
        422
    );

}


/*
|--------------------------------------------------------------------------
| Database
|--------------------------------------------------------------------------
*/

try {

    $db = getDatabaseConnection();


    /*
    |--------------------------------------------------------------------------
    | Check Category
    |--------------------------------------------------------------------------
    */

    $categoryStmt = $db->prepare(
        "
        SELECT
            id,
            name,
            slug

        FROM categories

        WHERE id = :id

        LIMIT 1
        "
    );


    $categoryStmt->execute([
        ':id' => $id
    ]);


    $category = $categoryStmt->fetch();


    if (!$category) {

        errorResponse(
            'القسم غير موجود.',
            404
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Check Products
    |--------------------------------------------------------------------------
    */

    $productsStmt = $db->prepare(
        "
        SELECT COUNT(*)

        FROM products

        WHERE category_id = :category_id
        "
    );


    $productsStmt->execute([
        ':category_id' => $id
    ]);


    $productsCount = (int)
        $productsStmt->fetchColumn();


    /*
    |--------------------------------------------------------------------------
    | Prevent Accidental Delete
    |--------------------------------------------------------------------------
    */

    if ($productsCount > 0) {

        errorResponse(
            'لا يمكن حذف القسم لأنه يحتوي على ' .
            $productsCount .
            ' منتج. انقل المنتجات إلى قسم آخر أولاً.',
            409,
            [
                'products_count' =>
                    $productsCount
            ]
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Delete
    |--------------------------------------------------------------------------
    */

    $deleteStmt = $db->prepare(
        "
        DELETE FROM categories

        WHERE id = :id
        "
    );


    $deleteStmt->execute([
        ':id' => $id
    ]);


    /*
    |--------------------------------------------------------------------------
    | Verify Delete
    |--------------------------------------------------------------------------
    */

    if ($deleteStmt->rowCount() === 0) {

        errorResponse(
            'تعذر حذف القسم.',
            500
        );

    }


    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [
            'deleted' => true,

            'category_id' => $id,

            'category_name' =>
                $category['name']

        ],
        'تم حذف القسم بنجاح.'
    );


} catch (PDOException $e) {

    error_log(
        'Delete Category PDO Error: ' .
        $e->getMessage()
    );


    /*
    |--------------------------------------------------------------------------
    | Foreign Key Protection
    |--------------------------------------------------------------------------
    */

    if ($e->getCode() === '23000') {

        errorResponse(
            'لا يمكن حذف القسم لأنه مرتبط ببيانات أخرى.',
            409
        );

    }


    errorResponse(
        'حدث خطأ أثناء حذف القسم.',
        500
    );


} catch (Throwable $e) {

    error_log(
        'Delete Category Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء حذف القسم.',
        500
    );

}
