<?php

/*
|--------------------------------------------------------------------------
| Al Baraka Mall
| Admin Logout API
|--------------------------------------------------------------------------
| File:
| api/v1/auth/logout.php
|--------------------------------------------------------------------------
*/


require_once __DIR__ . '/../../../config/config.php';

require_once __DIR__ . '/../../../config/database.php';

require_once __DIR__ . '/../../../config/auth.php';



/*
|--------------------------------------------------------------------------
| Initialize API
|--------------------------------------------------------------------------
*/

initializeApi();



/*
|--------------------------------------------------------------------------
| Allow POST Only
|--------------------------------------------------------------------------
*/

if (
    requestMethod() !== 'POST'
) {

    errorResponse(
        'طريقة الطلب غير مسموحة.',
        405
    );

}



/*
|--------------------------------------------------------------------------
| Check Login
|--------------------------------------------------------------------------
*/

if (
    !isAdminLoggedIn()
) {

    errorResponse(
        'لا توجد جلسة دخول نشطة.',
        401
    );

}



/*
|--------------------------------------------------------------------------
| CSRF Protection
|--------------------------------------------------------------------------
*/

requireCsrfToken();



/*
|--------------------------------------------------------------------------
| Get Current Admin
|--------------------------------------------------------------------------
*/

$admin =
    getCurrentAdmin();



/*
|--------------------------------------------------------------------------
| Logout
|--------------------------------------------------------------------------
*/

try {

    logoutAdmin();


    /*
    |--------------------------------------------------------------------------
    | Response
    |--------------------------------------------------------------------------
    */

    successResponse(
        [
            'logged_out' => true
        ],
        'تم تسجيل الخروج بنجاح.'
    );


} catch (
    Throwable $e
) {

    /*
    | تسجيل الخطأ داخليًا
    */

    error_log(
        'Admin Logout Error: ' .
        $e->getMessage()
    );


    errorResponse(
        'حدث خطأ أثناء تسجيل الخروج.',
        500
    );

}
